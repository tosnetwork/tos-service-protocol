const transportVectorPath = "testdata/transport-binding-v1-vectors.json"

type transportVectorFile struct {
	Schema  string                   `json:"schema"`
	Valid   []transportVectorValid   `json:"valid"`
	Invalid []transportVectorInvalid `json:"invalid"`
	Notes   []string                 `json:"notes"`
}

type transportVectorValid struct {
	Name            string `json:"name"`
	SecurityMode    uint8  `json:"security_mode"`
	MaxRequestBytes uint32 `json:"max_request_bytes"`
	BaseURL         string `json:"base_url"`
	BOCBase64       string `json:"boc_base64"`
	Digest          string `json:"transport_binding_digest"`
}

type transportVectorInvalid struct {
	Name            string `json:"name"`
	SecurityMode    uint8  `json:"security_mode"`
	MaxRequestBytes uint32 `json:"max_request_bytes"`
	BaseURL         string `json:"base_url"`
	BOCBase64       string `json:"boc_base64"`
}

// rawTransportCell encodes the NTB1 layout without validation, so refused
// bindings still have exact bytes a decoder must refuse.
func rawTransportCell(mode uint8, maximum uint32, baseURL string) *cell.Cell {
	return cell.BeginCell().MustStoreUInt(transportBindingMagic, 32).MustStoreUInt(quotePreimageSchema, 16).
		MustStoreUInt(uint64(mode), 8).MustStoreUInt(uint64(maximum), 32).MustStoreRef(stringCell(baseURL)).EndCell()
}

func buildTransportVectors(t *testing.T) transportVectorFile {
	t.Helper()
	provider := "agent_" + strings.Repeat("5a", 32)
	file := transportVectorFile{Schema: "tos.service.transport-binding.v1.vectors",
		Notes: []string{"generated by tos-service-protocol pkg/nativecore TestTransportBindingVectors",
			"invalid entries are NTB1 cells encoded without validation; every decoder must refuse them"}}
	for _, value := range []struct {
		name string
		v    TransportBindingV1
	}{
		{"connect-https", TransportBindingV1{TransportHTTPS, 1 << 20, "https://provider.example"}},
		{"connect-loopback", TransportBindingV1{TransportLoopbackHTTP, 16 << 20, "http://127.0.0.1:8080"}},
		{"agent-packet-1mib", TransportBindingV1{TransportAgentPacket, MaxAgentPacketTransportRequestBytes, "agent-packet:" + provider}},
		{"agent-packet-small", TransportBindingV1{TransportAgentPacket, 4096, "agent-packet:" + provider}},
	} {
		root, digest, err := BuildTransportBindingCellV1(value.v)
		if err != nil {
			t.Fatalf("%s: %v", value.name, err)
		}
		file.Valid = append(file.Valid, transportVectorValid{Name: value.name, SecurityMode: value.v.SecurityMode,
			MaxRequestBytes: value.v.MaxRequestBytes, BaseURL: value.v.BaseURL,
			BOCBase64: base64.StdEncoding.EncodeToString(root.ToBOC()), Digest: digest})
	}
	for _, value := range []struct {
		name string
		v    TransportBindingV1
	}{
		{"agent-packet-over-1mib", TransportBindingV1{TransportAgentPacket, MaxAgentPacketTransportRequestBytes + 1, "agent-packet:" + provider}},
		{"agent-packet-upper-hex", TransportBindingV1{TransportAgentPacket, 4096, "agent-packet:agent_" + strings.Repeat("5A", 32)}},
		{"agent-packet-short-id", TransportBindingV1{TransportAgentPacket, 4096, "agent-packet:agent_" + strings.Repeat("5a", 31)}},
		{"agent-packet-trailing", TransportBindingV1{TransportAgentPacket, 4096, "agent-packet:" + provider + "/"}},
		{"agent-packet-https-url", TransportBindingV1{TransportAgentPacket, 4096, "https://provider.example"}},
		{"https-naming-agent", TransportBindingV1{TransportHTTPS, 4096, "agent-packet:" + provider}},
		{"unknown-mode-3", TransportBindingV1{3, 4096, "agent-packet:" + provider}},
		{"agent-packet-zero-bound", TransportBindingV1{TransportAgentPacket, 0, "agent-packet:" + provider}},
		{"connect-https-over-16mib", TransportBindingV1{TransportHTTPS, 16<<20 + 1, "https://provider.example"}},
		{"connect-https-zero-bound", TransportBindingV1{TransportHTTPS, 0, "https://provider.example"}},
		{"connect-https-url-over-120-bytes", TransportBindingV1{TransportHTTPS, 4096, "https://" + strings.Repeat("a", 110) + ".example"}},
	} {
		root := rawTransportCell(value.v.SecurityMode, value.v.MaxRequestBytes, value.v.BaseURL)
		file.Invalid = append(file.Invalid, transportVectorInvalid{Name: value.name, SecurityMode: value.v.SecurityMode,
			MaxRequestBytes: value.v.MaxRequestBytes, BaseURL: value.v.BaseURL,
			BOCBase64: base64.StdEncoding.EncodeToString(root.ToBOC())})
	}
	return file
}

// TestTransportBindingVectors regenerates the frozen transport binding
// vectors and requires the committed file to equal them byte for byte;
// set TRANSPORT_BINDING_VECTOR_OUT to write a fresh copy. It also decodes
// every entry: valid ones round-trip, invalid ones are refused.
func TestTransportBindingVectors(t *testing.T) {
	file := buildTransportVectors(t)
	encoded, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	encoded = append(encoded, '\n')
	if out := os.Getenv("TRANSPORT_BINDING_VECTOR_OUT"); out != "" {
		if err := os.WriteFile(out, encoded, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	frozen, err := os.ReadFile(transportVectorPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(frozen, encoded) {
		t.Fatal("the frozen transport binding vectors differ from the implementation")
	}
	for _, entry := range file.Valid {
		raw, _ := base64.StdEncoding.DecodeString(entry.BOCBase64)
		root, err := cell.FromBOC(raw)
		if err != nil {
			t.Fatal(err)
		}
		decoded, err := DecodeTransportBindingCellV1(root)
		if err != nil || decoded != (TransportBindingV1{entry.SecurityMode, entry.MaxRequestBytes, entry.BaseURL}) {
			t.Fatalf("%s: decoded=%+v err=%v", entry.Name, decoded, err)
		}
	}
	for _, entry := range file.Invalid {
		raw, _ := base64.StdEncoding.DecodeString(entry.BOCBase64)
		root, err := cell.FromBOC(raw)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := DecodeTransportBindingCellV1(root); err == nil {
			t.Fatalf("%s: decoded a refused binding", entry.Name)
		}
	}
}
